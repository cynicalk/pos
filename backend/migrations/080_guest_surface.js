/*
 * Phase 7 — the guest surface (MERGE_PLAN.md).
 *
 * Allergens and diet are declared on the INGREDIENT, not on the dish.
 *
 * The source put both on the menu item, which means every dish containing
 * paneer has to be tagged "dairy" by hand, and the day someone adds a new
 * paneer dish and forgets, a guest with a dairy allergy is told it is safe.
 * The POS already knows which ingredients are in which dish — that is what
 * recipes are for — so declaring paneer as dairy once makes every dish built
 * from it correct, including the ones added next year.
 *
 * That inversion has a consequence the UI has to carry honestly: a dish with
 * NO recipe, or a recipe containing an ingredient nobody has classified, has
 * unknown allergens. Not "no allergens". The whole point of a dietary filter is
 * that a guest trusts it, so "we don't know" has to be a visible third state
 * rather than being rounded down to safe.
 *
 * `diet` is a single value per ingredient rather than a set of flags because
 * the values are ordered by restrictiveness (vegan ⊂ vegetarian ⊂ everything)
 * and a dish takes the least restrictive ingredient it contains. Flags would
 * let an ingredient be marked both vegan and non-vegetarian.
 *
 * NOT here: a nutrition column. See MERGE_PLAN.md — the POS holds no nutrition
 * data for anything, and a per-serving calorie count generated by a language
 * model is a fabricated number a guest might make a medical decision on. That
 * feature ships as a shell.
 */

exports.up = (pgm) => {
  pgm.sql(`
    ALTER TABLE ingredients
      -- Empty array = "declared, contains none of the known allergens".
      -- NULL      = "nobody has looked at this yet". The difference is the
      -- entire safety story, so the column is deliberately nullable with no
      -- default: a default of '{}' would silently declare every existing
      -- ingredient allergen-free.
      ADD COLUMN IF NOT EXISTS allergens TEXT[],
      ADD COLUMN IF NOT EXISTS diet TEXT
        CHECK (diet IS NULL OR diet IN ('vegan','vegetarian','non_vegetarian')),
      ADD COLUMN IF NOT EXISTS dietary_declared_at TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS dietary_declared_by UUID REFERENCES users(id) ON DELETE SET NULL;

    -- The guest menu's filter scans for ingredients still lacking a
    -- declaration; indexing the absence keeps that cheap.
    CREATE INDEX IF NOT EXISTS ingredients_undeclared_idx
      ON ingredients (restaurant_id)
      WHERE diet IS NULL OR allergens IS NULL;

    -- Cached translations, keyed by language code:
    --   { "hi": { "name": "...", "description": "..." }, ... }
    -- Cached so rendering the guest menu card costs zero model calls. The
    -- English source of truth stays in name/description; this is only ever a
    -- presentation layer over it.
    ALTER TABLE menu_items
      ADD COLUMN IF NOT EXISTS translations JSONB NOT NULL DEFAULT '{}'::jsonb;
  `);
};

exports.down = (pgm) => {
  pgm.sql(`
    ALTER TABLE menu_items DROP COLUMN IF EXISTS translations;
    DROP INDEX IF EXISTS ingredients_undeclared_idx;
    ALTER TABLE ingredients
      DROP COLUMN IF EXISTS dietary_declared_by,
      DROP COLUMN IF EXISTS dietary_declared_at,
      DROP COLUMN IF EXISTS diet,
      DROP COLUMN IF EXISTS allergens;
  `);
};
